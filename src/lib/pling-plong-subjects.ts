function shuffle<T>(values: T[]): T[] {
  for (let i = values.length - 1; i > 0; i--) {
    const j = rand(0, i);
    [values[i], values[j]] = [values[j]!, values[i]!];
  }
  return values;
}

export function parseCustomPlingQuestions(value: string): {
  questions: [string, string][];
  invalidLines: number[];
} {
  const questions: [string, string][] = [];
  const invalidLines: number[] = [];
  const seen = new Set<string>();

  value.split(/\r?\n/).forEach((line, index) => {
    if (!line.trim()) return;
    const separator = line.indexOf(";");
    if (separator < 0) {
      invalidLines.push(index + 1);
      return;
    }
    const text = line.slice(0, separator).trim();
    const answer = line.slice(separator + 1).trim();
    if (!text || !answer) {
      invalidLines.push(index + 1);
      return;
    }
    const normalizedQuestion = text.replace(/\s+/g, " ").toLocaleLowerCase("sv-SE");
    if (seen.has(normalizedQuestion)) {
      invalidLines.push(index + 1);
      return;
    }
    seen.add(normalizedQuestion);
    questions.push([text, answer]);
  });

  return { questions, invalidLines };
}

export function generateSubjectPlingPlong(options: {
  subject: PlingSubject;
  customQuestions?: readonly [string, string][];
  tiles: number;
  plingCount: number;
}): PlingQuestion[] {
  const source = options.customQuestions ?? COMPLETE_QUESTION_BANK[options.subject];
  const uniqueQuestions = new Map<string, [string, string]>(
    source.map(([text, answer]) => [
      text.replace(/\s+/g, " ").toLocaleLowerCase("sv-SE"),
      [text, answer] as [string, string],
    ]),
  );
  if (uniqueQuestions.size < options.tiles) {
    throw new RangeError(
      `At least ${options.tiles} unique questions are required to create this game.`,
    );
  }

  const plingCount = Math.max(0, Math.min(options.tiles, Math.round(options.plingCount)));
  const questions = shuffle([...uniqueQuestions.values()])
    .slice(0, options.tiles)
    .map(([text, answer], index) => ({
      text,
      answer,
      pling: index < plingCount,
      word: true,
      geo: false,
    }));

  return shuffle(questions);
}
