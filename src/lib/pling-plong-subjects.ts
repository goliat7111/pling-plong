function conceptQuestions(facts: readonly [string, string][]): [string, string][] {
  return facts.flatMap(([term, definition]) => [
    [`Förklara begreppet ${term}.`, definition],
    [`Vilket begrepp beskrivs så här: ${definition}?`, term],
  ]);
}

